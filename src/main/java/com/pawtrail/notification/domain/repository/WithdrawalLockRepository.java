package com.pawtrail.notification.domain.repository;

/**
 * 알림 만들기와 탈퇴 처리를 한 줄로 세우는 잠금입니다.
 *
 * 둘이 겹치면 이런 일이 생깁니다.
 * 알림 만들기가 설정을 "받음" 으로 읽고 아직 쓰기 전에 탈퇴가 표시를 찍고 알림을 지운 뒤 커밋하면,
 * 알림 만들기가 뒤이어 새 알림을 씁니다. 탈퇴 쪽 삭제는 이미 끝나 그 행은 영영 남습니다.
 * auth 는 탈퇴를 두 번 보내지 않으므로 지울 기회가 다시 오지 않습니다.
 * 설정 행이 없는 사람은 잠글 행이 없어 행 잠금으로도 막을 수 없습니다.
 *
 * 키 하나를 공유 · 배타로 나눠 잡습니다.
 *   알림 만들기   공유 — 만들기끼리는 서로 막지 않습니다.
 *   탈퇴          배타 — 진행 중인 만들기가 다 끝난 뒤에 돌고, 도는 동안 새 만들기가 기다립니다.
 * 그래서 탈퇴는 앞서 만들어진 알림까지 지우고, 뒤에 오는 만들기는 탈퇴 표시를 보고 건너뜁니다.
 *
 * 계정마다 잠그지 않는 이유는 조건 변경 한 건이 수천 명을 다루기 때문입니다.
 * 받는 사람마다 잠그면 잠금이 그만큼 쌓여 PostgreSQL 의 잠금 표 한도에 닿을 수 있습니다.
 * 탈퇴는 드물어 모두가 한 줄에 서도 기다림이 거의 없습니다.
 *
 * 쓰기 트랜잭션 안에서만 부릅니다. 잠금은 그 트랜잭션이 끝날 때 저절로 풀립니다.
 * 이벤트 경로는 Inbox 가 트랜잭션을 열고 있습니다.
 */
public interface WithdrawalLockRepository {

    /**
     * 알림을 만들기 전에 잡습니다. 탈퇴가 진행 중이면 그것이 끝날 때까지 기다립니다.
     */
    void lockForCreation();

    /**
     * 탈퇴를 처리하기 전에 잡습니다. 진행 중인 알림 만들기가 다 끝날 때까지 기다립니다.
     */
    void lockForWithdrawal();
}
